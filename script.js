/* ESTADO */
let idiomaActual = "es";
let menuVisible = false;


/* FUNCIONES AUXILIARES */
function ponerTexto(elemento, texto) {
  if (elemento && texto !== undefined && texto !== null) {
    elemento.textContent = texto;
  }
}

function traducirLista(elementos, textos) {
  elementos.forEach((elemento, indice) => {
    if (textos[indice] !== undefined) {
      ponerTexto(elemento, textos[indice]);
    }
  });
}

function traducirTitulo(seccion, texto) {
  if (!seccion) return;
  ponerTexto(seccion.querySelector("h2"), texto);
}


/* APLICAR TRADUCCIONES */
function aplicarIdioma(idioma) {
  const textos = idioma === "en" ? EN : ES;

  idiomaActual = idioma;
  document.documentElement.lang = idioma;

  /* MENÚ */
  traducirLista(
    document.querySelectorAll("#nav ul li a"),
    textos.nav
  );

  /* PRESENTACIÓN */
  ponerTexto(
    document.querySelector("#inicio h2"),
    textos.hero
  );

  /* SOBRE MÍ */
  const about = document.querySelector("#sobremi");

  if (about) {
    traducirTitulo(about, textos.aboutTitle);

    traducirLista(
      about.querySelectorAll(".contenido-seccion > p"),
      textos.aboutText
    );

    const columnas = about.querySelectorAll(".fila .col");

    if (columnas[0]) {
      ponerTexto(
        columnas[0].querySelector("h3"),
        textos.information[0]
      );

      const datos = columnas[0].querySelectorAll(".datos li");

      datos.forEach((dato, indice) => {
        ponerTexto(
          dato.querySelector("strong"),
          textos.information[indice + 1]
        );

        if (indice === 2) {
          ponerTexto(dato.querySelector("span"), textos.formation);
        }

        if (indice === 3) {
          ponerTexto(dato.querySelector("span"), textos.status);
        }
      });
    }

    if (columnas[1]) {
      ponerTexto(
        columnas[1].querySelector("h3"),
        textos.interestsTitle
      );

      traducirLista(
        columnas[1].querySelectorAll(".interes span"),
        textos.interests
      );
    }
  }

  /* HABILIDADES */
  const skills = document.querySelector("#skills");

  if (skills) {
    traducirTitulo(skills, textos.skillsTitle);

    const columnas = skills.querySelectorAll(".fila .col");

    if (columnas[0]) {
      ponerTexto(
        columnas[0].querySelector("h3"),
        textos.technical
      );

      traducirLista(
        columnas[0].querySelectorAll(".skill-nombre"),
        textos.technicalSkills
      );
    }

    if (columnas[1]) {
      ponerTexto(
        columnas[1].querySelector("h3"),
        textos.personal
      );

      traducirLista(
        columnas[1].querySelectorAll(".skill-nombre"),
        textos.personalSkills
      );
    }
  }

  /* FORMACIÓN Y PROYECTOS */
  const curriculum = document.querySelector("#curriculum");

  if (curriculum) {
    traducirTitulo(curriculum, textos.curriculumTitle);

    const columnas = curriculum.querySelectorAll(".fila > .col");

    if (columnas[0]) {
      ponerTexto(
        columnas[0].querySelector("h3"),
        textos.educationTitle
      );

      columnas[0].querySelectorAll(".item").forEach((item, indice) => {
        const datos = textos.education[indice];
        if (!datos) return;

        ponerTexto(item.querySelector("h4"), datos.title);
        ponerTexto(item.querySelector(".casa"), datos.place);
        ponerTexto(item.querySelector(".fecha"), datos.date);
        ponerTexto(item.querySelector("p"), datos.text);
      });
    }

    if (columnas[1]) {
      ponerTexto(
        columnas[1].querySelector("h3"),
        textos.projectsTitle
      );

      columnas[1].querySelectorAll(".item").forEach((item, indice) => {
        const datos = textos.projects[indice];
        if (!datos) return;

        ponerTexto(item.querySelector("h4"), datos.title);
        ponerTexto(item.querySelector("p"), datos.text);
      });
    }
  }

  /* PORTAFOLIO */
  const portfolio = document.querySelector("#portfolio");

  if (portfolio) {
    traducirTitulo(portfolio, textos.portfolioTitle);

    portfolio.querySelectorAll(".proyecto").forEach((proyecto, indice) => {
      const datos = textos.portfolio[indice];
      if (!datos) return;

      ponerTexto(proyecto.querySelector("h3"), datos[0]);
      ponerTexto(proyecto.querySelector("p"), datos[1]);
    });
  }

  /* CONTACTO */
  const contacto = document.querySelector("#contacto");

  if (contacto) {
    traducirTitulo(contacto, textos.contactTitle);

    ponerTexto(
      contacto.querySelector(".contacto-intro"),
      textos.contactText
    );

    const tarjetas = contacto.querySelectorAll(".tarjeta");

    if (tarjetas[0]) {
      ponerTexto(
        tarjetas[0].querySelector("strong"),
        textos.contactEmail
      );
    }

    if (tarjetas[2]) {
      ponerTexto(
        tarjetas[2].querySelector("span"),
        textos.contactLinkedin
      );
    }
  }

  /* PIE DE PÁGINA */
  ponerTexto(
    document.querySelector(".footer-nota"),
    textos.footer
  );

  /* BOTÓN DE IDIOMA */
  const boton = document.getElementById("btn-idioma");

  if (boton) {
    const otroIdioma = idioma === "es" ? "EN" : "ES";

    boton.innerHTML =
      '<span class="idioma-activo">' + idioma.toUpperCase() + "</span>" +
      '<span class="idioma-sep"> / </span>' +
      '<span class="idioma-inactivo">' + otroIdioma + "</span>";

    boton.setAttribute(
      "aria-label",
      idioma === "es" ? "Cambiar a inglés" : "Switch to Spanish"
    );
  }
}


/* BOTÓN DE IDIOMA */
function cambiarIdioma() {
  aplicarIdioma(idiomaActual === "es" ? "en" : "es");
}


/* MENÚ RESPONSIVE */
function mostrarOcultarMenu() {
  const nav = document.getElementById("nav");
  if (!nav) return;

  menuVisible = !nav.classList.contains("responsive");
  nav.classList.toggle("responsive", menuVisible);
}

function cerrarMenu() {
  const nav = document.getElementById("nav");
  if (!nav) return;

  nav.classList.remove("responsive");
  menuVisible = false;
}


/* ANIMACIÓN DE HABILIDADES */
function animarHabilidades() {
  const barras = document.querySelectorAll(".progreso");

  function mostrar(barra) {
    const porcentaje = barra.getAttribute("data-percent") || "0";

    barra.style.width = porcentaje + "%";

    ponerTexto(
      barra.querySelector("span"),
      porcentaje + "%"
    );
  }

  if (!("IntersectionObserver" in window)) {
    barras.forEach(mostrar);
    return;
  }

  const observador = new IntersectionObserver((entradas, obs) => {
    entradas.forEach(entrada => {
      if (entrada.isIntersecting) {
        mostrar(entrada.target);
        obs.unobserve(entrada.target);
      }
    });
  }, { threshold: 0.4 });

  barras.forEach(barra => observador.observe(barra));
}


/* EXPONER FUNCIONES PARA LOS BOTONES DEL HTML */
window.aplicarIdioma = aplicarIdioma;
window.cambiarIdioma = cambiarIdioma;
window.mostrarOcultarMenu = mostrarOcultarMenu;
window.cerrarMenu = cerrarMenu;


/* INICIALIZAR */
function iniciarPortafolio() {
  aplicarIdioma("es");
  animarHabilidades();

  const botonIdioma = document.getElementById("btn-idioma");

  if (botonIdioma) {
    botonIdioma.onclick = cambiarIdioma;
  }

  const botonMenu = document.querySelector(".nav-responsive");

  if (botonMenu) {
    botonMenu.onclick = mostrarOcultarMenu;
  }

  document.querySelectorAll("#nav ul li a").forEach(enlace => {
    enlace.addEventListener("click", cerrarMenu);
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", iniciarPortafolio);
} else {
  iniciarPortafolio();
}
