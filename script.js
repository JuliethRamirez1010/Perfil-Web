let idiomaActual = "es";


function aplicarIdioma(idioma) {

  const textos = idioma === "es" ? ES : EN;

  const nav = document.querySelectorAll("#nav ul li a");

  nav.forEach((elemento, indice) => {
    if (textos.nav[indice]) {
      elemento.textContent = textos.nav[indice];
    }
  });


  const hero = document.querySelector("#inicio h2");

  if (hero) {
    hero.textContent = textos.hero;
  }


  const about = document.querySelector("#sobremi");

  if (about) {

    const titulo = about.querySelector("h2");

    if (titulo) {
      titulo.textContent = textos.aboutTitle;
    }

    const parrafos = about.querySelectorAll(".contenido-seccion > p");

    parrafos.forEach((parrafo, indice) => {
      if (textos.aboutText[indice]) {
        parrafo.textContent = textos.aboutText[indice];
      }
    });


    const columnas = about.querySelectorAll(".fila .col");

    if (columnas.length >= 2) {

      const infoTitulo = columnas[0].querySelector("h3");

      if (infoTitulo) {
        infoTitulo.textContent = textos.information[0];
      }

      const datos = columnas[0].querySelectorAll(".datos li");

      if (datos[0]) {
        datos[0].querySelector("strong").textContent = textos.information[1];
      }

      if (datos[1]) {
        datos[1].querySelector("strong").textContent = textos.information[2];
      }

      if (datos[2]) {
        datos[2].querySelector("strong").textContent = textos.information[3];
        datos[2].querySelector("span").textContent = textos.formation;
      }

      if (datos[3]) {
        datos[3].querySelector("strong").textContent = textos.information[4];
        datos[3].querySelector("span").textContent = textos.status;
      }

      const interesesTitulo = columnas[1].querySelector("h3");

      if (interesesTitulo) {
        interesesTitulo.textContent = textos.interestsTitle;
      }

      const intereses = columnas[1].querySelectorAll(".interes span");

      intereses.forEach((elemento, indice) => {
        if (textos.interests[indice]) {
          elemento.textContent = textos.interests[indice];
        }
      });

    }
  }


  const skills = document.querySelector("#skills");

  if (skills) {

    const titulo = skills.querySelector("h2");

    if (titulo) {
      titulo.textContent = textos.skillsTitle;
    }

    const columnas = skills.querySelectorAll(".fila .col");

    if (columnas[0]) {
      const tituloTecnico = columnas[0].querySelector("h3");

      if (tituloTecnico) {
        tituloTecnico.textContent = textos.technical;
      }
    }

    if (columnas[1]) {

      const tituloPersonal = columnas[1].querySelector("h3");

      if (tituloPersonal) {
        tituloPersonal.textContent = textos.personal;
      }

      const habilidades = columnas[1].querySelectorAll(".skill-nombre");

      habilidades.forEach((elemento, indice) => {

        if (textos.personalSkills[indice]) {
          elemento.textContent = textos.personalSkills[indice];
        }

      });

    }

  }


  const curriculum = document.querySelector("#curriculum");

  if (curriculum) {

    const titulo = curriculum.querySelector("h2");

    if (titulo) {
      titulo.textContent = textos.curriculumTitle;
    }

    const columnas = curriculum.querySelectorAll(".fila > .col");

    if (columnas[0]) {

      const tituloEducacion = columnas[0].querySelector("h3");

      if (tituloEducacion) {
        tituloEducacion.textContent = textos.educationTitle;
      }

      const items = columnas[0].querySelectorAll(".item");

      items.forEach((item, indice) => {

        const datos = textos.education[indice];

        if (!datos) return;

        const h4 = item.querySelector("h4");
        const casa = item.querySelector(".casa");
        const fecha = item.querySelector(".fecha");
        const p = item.querySelector("p");

        if (h4) h4.textContent = datos.title;
        if (casa) casa.textContent = datos.place;
        if (fecha) fecha.textContent = datos.date;
        if (p) p.textContent = datos.text;

      });

    }


    if (columnas[1]) {

      const tituloProyectos = columnas[1].querySelector("h3");

      if (tituloProyectos) {
        tituloProyectos.textContent = textos.projectsTitle;
      }

      const items = columnas[1].querySelectorAll(".item");

      items.forEach((item, indice) => {

        const datos = textos.projects[indice];

        if (!datos) return;

        const h4 = item.querySelector("h4");
        const p = item.querySelector("p");

        if (h4) h4.textContent = datos.title;
        if (p) p.textContent = datos.text;

      });

    }

  }


  const portfolio = document.querySelector("#portfolio");

  if (portfolio) {

    const titulo = portfolio.querySelector("h2");

    if (titulo) {
      titulo.textContent = textos.portfolioTitle;
    }

    const proyectos = portfolio.querySelectorAll(".proyecto");

    proyectos.forEach((proyecto, indice) => {

      const datos = textos.portfolio[indice];

      if (!datos) return;

      const h3 = proyecto.querySelector("h3");
      const p = proyecto.querySelector("p");

      if (h3) h3.textContent = datos[0];
      if (p) p.textContent = datos[1];

    });

  }


  const contacto = document.querySelector("#contacto");

  if (contacto) {

    const titulo = contacto.querySelector("h2");

    if (titulo) {
      titulo.textContent = textos.contactTitle;
    }

    const intro = contacto.querySelector(".contacto-intro");

    if (intro) {
      intro.textContent = textos.contactText;
    }

    const tarjetas = contacto.querySelectorAll(".tarjeta");

    if (tarjetas[0]) {
      const strong = tarjetas[0].querySelector("strong");

      if (strong) {
        strong.textContent = textos.contactEmail;
      }
    }

    if (tarjetas[2]) {
      const span = tarjetas[2].querySelector("span");

      if (span) {
        span.textContent = textos.contactLinkedin;
      }
    }

  }


  const footer = document.querySelector(".footer-nota");

  if (footer) {
    footer.textContent = textos.footer;
  }


  document.documentElement.lang = idioma;


  const boton = document.getElementById("btn-idioma");

  if (boton) {

    const otroIdioma = idioma === "es" ? "EN" : "ES";

    boton.innerHTML =
      '<span class="idioma-activo">' +
      idioma.toUpperCase() +
      '</span>' +
      '<span class="idioma-sep">/</span>' +
      '<span class="idioma-inactivo">' +
      otroIdioma +
      '</span>';

    boton.setAttribute(
      "aria-label",
      idioma === "es"
        ? "Cambiar a inglés"
        : "Switch to Spanish"
    );

  }


  idiomaActual = idioma;

}


function cambiarIdioma() {

  if (idiomaActual === "es") {
    aplicarIdioma("en");
  } else {
    aplicarIdioma("es");
  }

}


let menuVisible = false;


function mostrarOcultarMenu() {

  const nav = document.getElementById("nav");

  if (!nav) return;

  menuVisible = !menuVisible;

  nav.className = menuVisible ? "responsive" : "";

}


function cerrarMenu() {

  const nav = document.getElementById("nav");

  if (!nav) return;

  nav.className = "";
  menuVisible = false;

}


function animarHabilidades() {

  const barras = document.querySelectorAll(".progreso");

  const mostrar = barra => {

    const porcentaje =
      barra.getAttribute("data-percent") || "0";

    barra.style.width = porcentaje + "%";

    const etiqueta = barra.querySelector("span");

    if (etiqueta) {
      etiqueta.textContent = porcentaje + "%";
    }

  };


  if (!("IntersectionObserver" in window)) {

    barras.forEach(mostrar);
    return;

  }


  const observador = new IntersectionObserver(
    (entradas, obs) => {

      entradas.forEach(entrada => {

        if (entrada.isIntersecting) {

          mostrar(entrada.target);

          obs.unobserve(entrada.target);

        }

      });

    },
    {
      threshold: 0.4
    }
  );


  barras.forEach(barra => observador.observe(barra));

}


document.addEventListener("DOMContentLoaded", () => {

  aplicarIdioma("es");

  animarHabilidades();

});
